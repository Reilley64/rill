"""Generate frozen XID tables from the approved Unicode 17 input, not host Unicode.

Usage: mise exec -- python crates/compiler/tools/generate_unicode.py <DerivedCoreProperties.txt>
The input can be downloaded separately from the URL below. Generation verifies its
approved full-file digest. Neither builds nor tests download Unicode data.
"""

import hashlib
from pathlib import Path
import sys

URL = "https://www.unicode.org/Public/17.0.0/ucd/DerivedCoreProperties.txt"
SHA256 = "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08"
data = Path(sys.argv[1]).read_bytes()
if hashlib.sha256(data).hexdigest() != SHA256:
    raise SystemExit("Unicode input digest differs from the approved baseline")
ranges = {"XID_Start": [], "XID_Continue": []}
for line in data.decode("utf-8").splitlines():
    fields = line.split("#")[0].strip().split(";")
    if len(fields) != 2 or fields[1].strip() not in ranges:
        continue
    bounds = fields[0].strip().split("..")
    ranges[fields[1].strip()].append((int(bounds[0], 16), int(bounds[-1], 16)))
out = [
    "// Generated by tools/generate_unicode.py; do not use host Unicode properties.",
    f"// Unicode 17.0.0: {URL}",
    f"// Approved source SHA-256: {SHA256}",
    "// Unicode data license: ../UNICODE-LICENSE.txt",
    "",
    "fn contains(ranges: &[(u32, u32)], c: char) -> bool {",
    "    let c = c as u32;",
    "    let i = ranges.partition_point(|&(_, end)| end < c);",
    "    ranges.get(i).is_some_and(|&(start, _)| start <= c)",
    "}",
    "",
    "pub(crate) fn start(c: char) -> bool {",
    "    c == '_' || contains(START, c)",
    "}",
    "pub(crate) fn continue_(c: char) -> bool {",
    "    contains(CONTINUE, c)",
    "}",
]
for prop, name in [("XID_Start", "START"), ("XID_Continue", "CONTINUE")]:
    out.append(f"const {name}: &[(u32, u32)] = &[")
    for start, end in ranges[prop]:
        out.append(f"    (0x{start:X}, 0x{end:X}),")
    out.append("];\n")
Path(__file__).resolve().parents[1].joinpath("src/unicode.rs").write_text("\n".join(out))
